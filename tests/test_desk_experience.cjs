const assert=require('node:assert/strict');
const {normalize,essentials,collapse,panelTitle}=require('../static/desk_experience.js');
const {concentration,relevantNews}=require('../static/desk_brief.js');
const {explain}=require('../static/desk_connections.js');
assert.match(explain({status:'stale',error:'old error'}),/old/);
assert.match(explain({error:'HTTP 429'}),/slow down/);
assert.match(explain({error:'HTTP 402'}),/spending limit/);
assert.match(explain({error:'HTTP 403'}),/denied/);
assert.match(explain({configured:false}),/missing/);
assert.deepEqual(normalize({skin:'javascript:bad',detail:'other'}),{skin:'plain',detail:'focused',portraits:true});
assert.equal(normalize({}).detail,'focused','Simple view is the default');
assert.equal(normalize({detail:'full'}).detail,'full','a saved Everything choice is kept');
for(const page of ['overview','auto','paper','research','ticket','settings'])assert.ok(essentials[page].length,'every page keeps its essentials: '+page);
assert.ok(essentials.auto.includes('#live-switch')&&essentials.overview.includes('#live-switch'),'the live trading switch is never folded away');
assert.ok(!Object.values(collapse).flat().some(rule=>/live-switch|beginner-ticket-wrap|broker-orders|opp-panel/.test(rule)),'orders, tickets and waiting ideas stay visible');
const heading=t=>({querySelector:()=>({textContent:t})});
assert.equal(panelTitle(heading('▸ Latest research call')),'Latest research call');
assert.equal(panelTitle(heading('Paper decision history?')),'Paper decision history');
assert.equal(normalize({}).skin,'desert','existing users keep the current appearance');
assert.equal(normalize({skin:'plain',detail:'focused',portraits:false}).portraits,false);
assert.equal(concentration({ok:true,equity:100,currency:'EUR',positions:[]}).available,false);
const c=concentration({ok:true,equity:100,currency:'USD',positions:[{ticker:'A',shares:1,last:30},{ticker:'B',shares:2,last:90,mark_is_cost_basis:true},{ticker:'A',shares:1,last:20,side:'short'}]});
assert.equal(c.rows[0].percent,50);assert.equal(c.missing,1);
assert.equal(concentration({ok:true,equity:0,currency:'USD'}).available,false);
const ts=Date.now(),stories=[{title:'AAPL: results reported',fresh:true,published_ts:ts/1000-60},{title:'AAPL - results reported',fresh:true,published_ts:ts/1000-50},{title:'A story for ALL investors',fresh:true,published_ts:ts/1000-30},{title:'MSFT future data',fresh:true,published_ts:ts/1000+100}];
assert.equal(relevantNews(stories,new Set(['AAPL','ALL','MSFT']),ts).length,1);
console.log('Theme fallback, view preferences, missing/cost-basis/currency concentration, duplicate news and future dates passed.');
